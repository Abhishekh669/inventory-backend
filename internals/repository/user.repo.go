package repository

import (
	"context"
	"errors"
	"fmt"
	"inventory/internals/config"
	"inventory/internals/database"
	"inventory/internals/helpers"
	"inventory/internals/models"
	"log"
	"time"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

type UserRepo interface {
	ScanUser(row pgx.Row) *models.User
	GetUserByEmail(ctx context.Context, email string) (*models.User, error)
	GetUserById(ctx context.Context, userId uuid.UUID) (*models.User, error)
	CreateUser(ctx context.Context, user *models.User) error
	EnsureAdminExists(ctx context.Context) error
}

type userRepo struct {
	pool *pgxpool.Pool
}

const userColumns = `id, name, email, password, gender, role, phone,
	last_password_reset_at, created_at, last_login_at`

// ScanUser scans a single row into a models.User.
// It returns nil if the row could not be scanned (including pgx.ErrNoRows).
func (u *userRepo) ScanUser(row pgx.Row) *models.User {
	var user models.User
	var lastLoginAt *time.Time // last_login_at is nullable in the schema

	err := row.Scan(
		&user.ID,
		&user.Name,
		&user.Email,
		&user.Password,
		&user.Gender,
		&user.Role,
		&user.Phone,
		&user.LastPasswordResetAt,
		&user.CreatedAt,
		&lastLoginAt,
	)
	if err != nil {
		return nil
	}

	if lastLoginAt != nil {
		user.LastLoginAt = *lastLoginAt
	}
	return &user
}

// GetUserByEmail retrieves a user by their email address.
func (u *userRepo) GetUserByEmail(ctx context.Context, email string) (*models.User, error) {
	query := `SELECT ` + userColumns + ` FROM users WHERE email = $1`

	user := u.ScanUser(u.pool.QueryRow(ctx, query, email))
	if user == nil {
		return nil, fmt.Errorf("user with email %q not found", email)
	}
	return user, nil
}

// GetUserById retrieves a user by their UUID.
func (u *userRepo) GetUserById(ctx context.Context, userId uuid.UUID) (*models.User, error) {
	query := `SELECT ` + userColumns + ` FROM users WHERE id = $1`

	user := u.ScanUser(u.pool.QueryRow(ctx, query, userId))
	if user == nil {
		return nil, fmt.Errorf("user with id %s not found", userId)
	}
	return user, nil
}

// CreateUser inserts a new user into the database.
// The id and created_at fields are generated by the database and written back
// into the provided user struct. The "role" column defaults to 'cashier'.
func (u *userRepo) CreateUser(ctx context.Context, user *models.User) error {
	query := `
		INSERT INTO users (name, email, gender, password, phone, last_password_reset_at)
		VALUES ($1, $2, $3, $4, $5, $6)
		RETURNING id, created_at, role`

	err := u.pool.QueryRow(ctx, query,
		user.Name,
		user.Email,
		user.Gender,
		user.Password, // must already be hashed
		user.Phone,
		user.LastPasswordResetAt,
	).Scan(&user.ID, &user.CreatedAt, &user.Role)
	if err != nil {
		return fmt.Errorf("create user: %w", err)
	}
	return nil
}

// EnsureAdminExists checks whether a user with the configured admin email
// exists and creates one with role = 'admin' if it does not.
// It is safe to call on every startup, including from multiple instances at once.
func (u *userRepo) EnsureAdminExists(ctx context.Context) error {
	cfg := config.AppConfig

	if cfg.AdminEmail == "" || cfg.AdminPassword == "" {
		return errors.New("admin email and password must be set in config")
	}

	// Cheap check first, so we skip the expensive password hash on normal startups.
	var exists bool
	err := u.pool.QueryRow(ctx,
		`SELECT EXISTS (SELECT 1 FROM users WHERE email = $1)`,
		cfg.AdminEmail,
	).Scan(&exists)
	if err != nil {
		return fmt.Errorf("failed to check admin existence: %w", err)
	}
	if exists {
		log.Println("Admin user already exists")
		return nil
	}

	hashedPassword, err := helpers.HashPassword(cfg.AdminPassword)
	if err != nil {
		return fmt.Errorf("failed to hash admin password: %w", err)
	}

	// ON CONFLICT covers the race where another instance inserts the admin
	// between our SELECT and this INSERT.
	const query = `
		INSERT INTO users (name, email, password, gender, phone, last_password_reset_at, role, last_login_at)
		VALUES ($1, $2, $3, $4, $5, $6, 'admin',$7)
		ON CONFLICT (email) DO NOTHING
		RETURNING id`

	var adminID uuid.UUID
	err = u.pool.QueryRow(ctx, query,
		"Admin",
		cfg.AdminEmail,
		hashedPassword,
		models.GenderMale,
		cfg.AdminPhone,
		time.Now().Unix(),
		time.Now(),
	).Scan(&adminID)
	if errors.Is(err, pgx.ErrNoRows) {
		// Conflict: someone else created it first. That's fine.
		log.Println("Admin user already exists")
		return nil
	}
	if err != nil {
		return fmt.Errorf("failed to create admin user: %w", err)
	}

	log.Printf("Admin user created successfully (id=%s)", adminID)
	return nil
}

// NewUserRepository creates a new user repository backed by the shared pgx pool.
func NewUserRepository() UserRepo {
	pool, err := database.GetPostgresPool()
	if err != nil {
		log.Println("Failed to initialize pool pool:", err)
		return nil
	}

	return &userRepo{
		pool: pool,
	}
}
